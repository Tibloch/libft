#include "libft.h"
#include <stdlib.h>

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*tmp;
	t_list	*next;

	tmp = *lst;
	next = tmp->next;
	while (tmp)
	{
		(*del)(tmp->content);
		free(tmp);
		tmp = next;
	}
}
